    /**
     * SOCSO row for a wage: (from < wage <= to), wage at/above the ceiling uses the last
     * row, wage at/below zero uses the first row.
     *
     * @return array{c1_employer: float, c1_employee_invalidity: float, c1_employee_skbbk: float, c2_employer: float, c2_employee_skbbk: float}
     */
    public static function socsoRow(float $wage): array
    {
        $row = self::findRow(self::SOCSO, $wage);

        return [
            'c1_employer' => $row[2],
            'c1_employee_invalidity' => $row[3],
            'c1_employee_skbbk' => $row[4],
            'c2_employer' => $row[5],
            'c2_employee_skbbk' => $row[6],
        ];
    }

    /**
     * EIS row for a wage: same band rule as socsoRow().
     *
     * @return array{employer: float, employee: float}
     */
    public static function eisRow(float $wage): array
    {
        $row = self::findRow(self::EIS, $wage);

        return ['employer' => $row[2], 'employee' => $row[3]];
    }

    /**
     * @param  list<array{0: float, 1: float|null, 2: float, 3: float, 4?: float, 5?: float, 6?: float}>  $table
     * @return array{0: float, 1: float|null, 2: float, 3: float, 4?: float, 5?: float, 6?: float}
     */
    private static function findRow(array $table, float $wage): array
    {
        if ($wage <= 0.0) {
            return $table[0];
        }

        foreach ($table as $row) {
            if ($row[1] === null || ($wage > $row[0] && $wage <= $row[1])) {
                return $row;
            }
        }

        return $table[count($table) - 1];
    }
