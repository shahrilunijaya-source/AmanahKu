<h1>Privacy Policy</h1>
<p class="updated">Last updated: 15 September 2026</p>

<p>AmanahKu is an HR and work management app operated by <strong>Unijaya Resources Sdn Bhd</strong> ("we", "us"). Companies use AmanahKu to run leave, claims, attendance, payroll, timesheets and day-to-day work for their staff. This policy explains what information AmanahKu holds, why, and what you can do about it. We handle personal data in line with Malaysia's Personal Data Protection Act 2010.</p>

<h2>Who is responsible for your data</h2>
<p>If you use AmanahKu as a member of staff, your employer decides what information is recorded about you and who in the company can see it. We run the app on their behalf. For questions about your own employment records, speak to your company's HR first. For anything about the app itself, contact us at the address below.</p>

<h2>What we collect</h2>
<ul>
  <li><strong>Account details:</strong> your name, email address, password (stored scrambled, never readable) and two-factor sign-in settings.</li>
  <li><strong>Employment records your company enters:</strong> job title, department, reporting line, employment dates, contact details, family and emergency contacts, education, documents, and identity numbers.</li>
  <li><strong>Pay and benefits:</strong> salary, allowances, deductions, statutory contributions (EPF, SOCSO, EIS, tax), payslips and bank details, where your company runs payroll in AmanahKu.</li>
  <li><strong>Requests and approvals:</strong> leave, claims and receipts, overtime, travel and other requests, with who approved them and when.</li>
  <li><strong>Attendance:</strong> clock-in and clock-out times, the location of your device at that moment, and, where your company uses it, a photo taken when you clock in or out. Photos are kept in private storage and are only visible to you and the people your company allows (for example your manager or HR).</li>
  <li><strong>Work:</strong> tasks, timesheets, comments, files you upload, training records and similar content you or your colleagues create.</li>
  <li><strong>Technical information:</strong> sign-in cookies, and error reports when something breaks in the app.</li>
</ul>

<h2>How we use it</h2>
<ul>
  <li>To run the features your company uses: approvals, payroll, attendance, reminders and reports.</li>
  <li>To send you emails the app needs to send, such as account invitations, password resets and approval notices.</li>
  <li>To keep the app secure, including a history of important changes so they can be checked later.</li>
  <li>To find and fix problems.</li>
</ul>
<p>We do not sell your data, and we do not use it for advertising.</p>

<h2>Google Calendar</h2>
<p>Connecting Google Calendar is optional, and each person decides for themselves from their own Profile page. If you connect:</p>
<ul>
  <li>AmanahKu creates a separate calendar named <strong>"Amanahku"</strong> in your Google account. It never reads, changes or deletes events in your main calendar or any other calendar.</li>
  <li>Your AmanahKu cards that have a due date are added to that calendar, and kept up to date when they change.</li>
  <li>AmanahKu reads changes made inside the "Amanahku" calendar (for example an event moved to another day) so the matching card can be updated.</li>
  <li>The access Google gives us is stored encrypted and is used only for this. It is not shared with anyone else, and it is not used for advertising or to train AI.</li>
  <li>You can stop at any time with <strong>Disconnect</strong> on your Profile page, which deletes the stored access, or by removing AmanahKu from your Google account's security settings.</li>
</ul>
<p>AmanahKu's use and transfer of information received from Google APIs follows the <a href="https://developers.google.com/terms/api-services-user-data-policy" rel="noopener">Google API Services User Data Policy</a>, including the Limited Use requirements.</p>

<h2>Services we rely on</h2>
<p>Some work is done by outside services, which only receive what they need for their job:</p>
<ul>
  <li><strong>Cloud hosting</strong> for the app and its database.</li>
  <li><strong>An email delivery service</strong> to send the app's emails.</li>
  <li><strong>An error monitoring service</strong> that receives technical details when something breaks. It is set up not to collect personal details such as your IP address.</li>
  <li><strong>Google</strong>, only if you connect Google Calendar.</li>
  <li><strong>An AI provider</strong>, only if your company turns on the AI assistant. It receives the question asked and the information needed to answer it.</li>
</ul>
<p>We may also share information when the law requires it.</p>

<h2>Cookies</h2>
<p>AmanahKu uses only the cookies it needs to keep you signed in and to protect forms. Your browser also remembers small preferences, such as language. There are no advertising or tracking cookies.</p>

<h2>How long we keep it</h2>
<p>Records are kept while your company uses AmanahKu, and for as long as your company needs them for employment, payroll, tax and legal reasons. The history of important changes is kept permanently so records can be checked. When a company stops using AmanahKu, its data can be removed on request, apart from anything the law requires us to keep.</p>

<h2>Keeping it safe</h2>
<p>Passwords are stored scrambled, sensitive fields such as identity numbers and Google access are encrypted, each company's data is kept apart from other companies', and you can turn on two-factor sign-in. No system is perfectly secure, but we work to protect what you trust us with.</p>

<h2>Your choices</h2>
<ul>
  <li>See and update your own details from your Profile page.</li>
  <li>Ask your company's HR to correct employment records.</li>
  <li>Ask us for a copy of your data, to correct it, or to limit how it is used, by emailing the address below.</li>
  <li>Disconnect Google Calendar at any time.</li>
</ul>

